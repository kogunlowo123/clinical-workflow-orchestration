"""Platform Ed25519 key: signs clinician sign-off attestations and the audit chain.

The private key is mounted from the cloud secret manager (never generated by
Terraform, never logged). Its public half is published at
``/.well-known/jwks.json`` so anyone holding a FHIR Provenance resource can
verify the sign-off signature it carries.
"""

from __future__ import annotations

import base64
from pathlib import Path
from typing import Any

import jwt
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey


class PlatformKey:
    def __init__(self, private_key: Ed25519PrivateKey, key_id: str) -> None:
        self._key = private_key
        self.key_id = key_id

    @classmethod
    def ephemeral(cls) -> PlatformKey:
        return cls(Ed25519PrivateKey.generate(), "ephemeral")

    @classmethod
    def from_file(cls, path: Path) -> PlatformKey:
        key = serialization.load_pem_private_key(path.read_bytes(), password=None)
        if not isinstance(key, Ed25519PrivateKey):
            raise ValueError("platform signing key must be Ed25519")
        return cls(key, path.stem)

    def sign(self, data: bytes) -> bytes:
        """Raw Ed25519 signature (the agentic-core audit chain Signer protocol)."""
        return self._key.sign(data)

    def sign_jws(self, claims: dict[str, Any]) -> str:
        return jwt.encode(
            claims, self._key, algorithm="EdDSA", headers={"kid": self.key_id, "typ": "JWT"}
        )

    def verify_jws(self, token: str) -> dict[str, Any]:
        claims: dict[str, Any] = jwt.decode(
            token,
            self._key.public_key(),
            algorithms=["EdDSA"],
            options={"verify_aud": False, "require": ["iat"]},
        )
        return claims

    def jwks(self) -> dict[str, Any]:
        raw = self._key.public_key().public_bytes(
            serialization.Encoding.Raw, serialization.PublicFormat.Raw
        )
        return {
            "keys": [
                {
                    "kty": "OKP",
                    "crv": "Ed25519",
                    "x": base64.urlsafe_b64encode(raw).rstrip(b"=").decode(),
                    "kid": self.key_id,
                    "alg": "EdDSA",
                    "use": "sig",
                }
            ]
        }

    @property
    def public_key(self) -> Any:
        return self._key.public_key()
